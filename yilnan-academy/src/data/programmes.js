export const programmesFor = (school) => PROGRAMMES.filter((p) => p.school === school)
export const programmeBySlug = (slug) => PROGRAMMES.find((p) => p.slug === slug)

export const formatFee = (fee) => {
  if (fee == null) return 'Announced soon'
  const n = (v) => '₦' + v.toLocaleString('en-NG')
  if (Array.isArray(fee)) return `${n(fee[0])} – ${n(fee[1])}`
  return n(fee)
}
